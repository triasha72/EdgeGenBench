"""Physics-based validation of surrogate-optimized designs."""

from __future__ import annotations

import json
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import yaml

from edgegenbench.models.preprocessing import FEATURE_COLUMNS
from edgegenbench.physics.synthetic_aircraft import simulate_designs

DEFAULT_VALIDATION_TARGETS = (
    "estimated_takeoff_mass_kg",
    "mission_energy_kwh",
    "energy_per_passenger_km_kwh",
    "lifecycle_emissions_proxy_kgco2e",
    "operating_cost_proxy_usd",
    "noise_proxy_db",
    "battery_fraction_margin",
    "takeoff_mass_margin_kg",
    "hydrogen_tank_volume_margin_m3",
)

DEFAULT_PLOT_TARGETS = (
    "lifecycle_emissions_proxy_kgco2e",
    "operating_cost_proxy_usd",
    "noise_proxy_db",
)


@dataclass(frozen=True)
class PhysicsValidationArtifacts:
    """Files and metrics generated by physics validation."""

    details_path: Path
    metrics_path: Path
    summary_path: Path
    plot_paths: tuple[Path, ...]
    design_count: int
    validated_target_count: int
    feasibility_agreement_rate: float


def _load_benchmark_config(
    config_path: Path,
) -> tuple[dict[str, Any], int]:
    """Load simulation constraints and reproducibility seed."""
    if not config_path.exists():
        raise FileNotFoundError(f"Benchmark configuration does not exist: {config_path}")

    with config_path.open(encoding="utf-8") as config_file:
        config = yaml.safe_load(config_file)

    if not isinstance(config, dict):
        raise ValueError("Benchmark configuration must contain a YAML mapping.")

    constraints = config.get("constraints")
    dataset = config.get("dataset")

    if not isinstance(constraints, dict):
        raise ValueError("Benchmark configuration is missing constraints.")

    if not isinstance(dataset, dict):
        raise ValueError("Benchmark configuration is missing dataset metadata.")

    seed = int(dataset.get("seed", 42))

    return constraints, seed


def _load_designs(
    designs_path: Path,
) -> pd.DataFrame:
    """Load optimized designs and validate their inputs."""
    if not designs_path.exists():
        raise FileNotFoundError(f"Optimized design file does not exist: {designs_path}")

    designs = pd.read_csv(designs_path)

    if designs.empty:
        raise ValueError("Optimized design file does not contain any rows.")

    missing_columns = sorted(set(FEATURE_COLUMNS).difference(designs.columns))

    if missing_columns:
        raise ValueError(f"Optimized designs are missing feature columns: {missing_columns}")

    if (
        designs.loc[
            :,
            list(FEATURE_COLUMNS),
        ]
        .isna()
        .any()
        .any()
    ):
        raise ValueError("Optimized design inputs contain missing values.")

    return designs


def _select_validation_targets(
    designs: pd.DataFrame,
    physics_outputs: pd.DataFrame,
    targets: Sequence[str],
) -> tuple[str, ...]:
    """Select targets available from both prediction and physics."""
    requested_targets = tuple(targets)

    if not requested_targets:
        raise ValueError("At least one validation target must be supplied.")

    available_targets = tuple(
        target
        for target in requested_targets
        if (target in designs.columns and target in physics_outputs.columns)
    )

    if not available_targets:
        raise ValueError(
            "No requested validation target exists in both "
            "the optimized designs and physics outputs."
        )

    return available_targets


def _calculate_target_metrics(
    details: pd.DataFrame,
    targets: Sequence[str],
) -> pd.DataFrame:
    """Calculate prediction-versus-physics metrics."""
    records: list[dict[str, float | int | str]] = []

    for target in targets:
        surrogate_values = details[f"surrogate_{target}"].to_numpy(dtype=np.float64)

        physics_values = details[f"physics_{target}"].to_numpy(dtype=np.float64)

        errors = surrogate_values - physics_values
        absolute_errors = np.abs(errors)

        scale = np.maximum(
            np.abs(physics_values),
            np.finfo(np.float64).eps,
        )

        relative_errors = absolute_errors / scale

        if (
            len(surrogate_values) > 1
            and np.std(surrogate_values) > np.finfo(np.float64).eps
            and np.std(physics_values) > np.finfo(np.float64).eps
        ):
            correlation = float(
                np.corrcoef(
                    surrogate_values,
                    physics_values,
                )[0, 1]
            )
        else:
            correlation = float("nan")

        records.append(
            {
                "target": target,
                "sample_count": int(len(surrogate_values)),
                "mae": float(np.mean(absolute_errors)),
                "rmse": float(np.sqrt(np.mean(errors**2))),
                "mean_signed_error": float(np.mean(errors)),
                "mean_relative_error": float(np.mean(relative_errors)),
                "max_relative_error": float(np.max(relative_errors)),
                "correlation": correlation,
            }
        )

    return pd.DataFrame(records)


def _plot_prediction_comparison(
    details: pd.DataFrame,
    target: str,
    output_path: Path,
) -> Path:
    """Plot surrogate predictions against physics results."""
    surrogate_values = details[f"surrogate_{target}"].to_numpy(dtype=np.float64)

    physics_values = details[f"physics_{target}"].to_numpy(dtype=np.float64)

    combined_values = np.concatenate(
        [
            surrogate_values,
            physics_values,
        ]
    )

    lower_limit = float(np.min(combined_values))
    upper_limit = float(np.max(combined_values))

    if np.isclose(
        lower_limit,
        upper_limit,
    ):
        padding = max(
            abs(lower_limit) * 0.05,
            1.0,
        )
        lower_limit -= padding
        upper_limit += padding

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    figure, axis = plt.subplots(figsize=(7, 6))

    axis.scatter(
        physics_values,
        surrogate_values,
        s=55,
    )

    axis.plot(
        [lower_limit, upper_limit],
        [lower_limit, upper_limit],
        linestyle="--",
        label="Perfect agreement",
    )

    for row_index, row in details.iterrows():
        label = str(
            row.get(
                "representative_role",
                row.get(
                    "candidate_id",
                    row_index,
                ),
            )
        )

        axis.annotate(
            label,
            (
                physics_values[row_index],
                surrogate_values[row_index],
            ),
            xytext=(4, 4),
            textcoords="offset points",
            fontsize=8,
        )

    axis.set_xlim(
        lower_limit,
        upper_limit,
    )
    axis.set_ylim(
        lower_limit,
        upper_limit,
    )

    axis.set_title(f"Surrogate vs Physics: {target}")
    axis.set_xlabel("Physics-model value")
    axis.set_ylabel("Surrogate prediction")
    axis.grid(alpha=0.3)
    axis.legend()

    figure.tight_layout()
    figure.savefig(
        output_path,
        dpi=160,
    )
    plt.close(figure)

    return output_path


def _json_safe(
    value: Any,
) -> Any:
    """Convert NumPy and nonfinite values for JSON output."""
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}

    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]

    if isinstance(value, np.integer):
        return int(value)

    if isinstance(value, np.floating):
        value = float(value)

    if isinstance(value, float):
        if not np.isfinite(value):
            return None

        return value

    return value


def validate_optimization_designs(
    designs_path: Path,
    benchmark_config_path: Path = Path("configs/v0_1.yaml"),
    output_dir: Path = Path("artifacts/optimization_validation"),
    targets: Sequence[str] = DEFAULT_VALIDATION_TARGETS,
    plot_targets: Sequence[str] = DEFAULT_PLOT_TARGETS,
) -> PhysicsValidationArtifacts:
    """Re-evaluate optimized designs with the physics model."""
    designs = _load_designs(designs_path)

    constraints, seed = _load_benchmark_config(benchmark_config_path)

    feature_frame = designs.loc[
        :,
        list(FEATURE_COLUMNS),
    ].copy()

    physics_outputs = simulate_designs(
        designs=feature_frame,
        constraints=constraints,
        seed=seed,
    ).reset_index(drop=True)

    designs = designs.reset_index(drop=True)

    validation_targets = _select_validation_targets(
        designs=designs,
        physics_outputs=physics_outputs,
        targets=targets,
    )

    metadata_columns = [
        column
        for column in (
            "representative_role",
            "selection_score",
            "pareto_rank",
            "candidate_id",
            *FEATURE_COLUMNS,
            "feasibility_probability",
            "feasibility_threshold",
            "predicted_is_feasible",
        )
        if column in designs.columns
    ]

    details = designs.loc[
        :,
        metadata_columns,
    ].copy()

    for target in validation_targets:
        surrogate_values = designs[target].to_numpy(dtype=np.float64)

        physics_values = physics_outputs[target].to_numpy(dtype=np.float64)

        errors = surrogate_values - physics_values

        details[f"surrogate_{target}"] = surrogate_values

        details[f"physics_{target}"] = physics_values

        details[f"signed_error_{target}"] = errors

        details[f"absolute_error_{target}"] = np.abs(errors)

        details[f"relative_error_{target}"] = np.abs(errors) / np.maximum(
            np.abs(physics_values),
            np.finfo(np.float64).eps,
        )

    details["physics_is_feasible"] = physics_outputs["is_feasible"].astype(bool)

    if "predicted_is_feasible" in designs.columns:
        classifier_feasibility = designs["predicted_is_feasible"].astype(bool)

        details["classifier_is_feasible"] = classifier_feasibility

        details["feasibility_agreement"] = classifier_feasibility == details["physics_is_feasible"]

        feasibility_agreement_rate = float(details["feasibility_agreement"].mean())
    else:
        details["classifier_is_feasible"] = True

        details["feasibility_agreement"] = details["physics_is_feasible"]

        feasibility_agreement_rate = float(details["physics_is_feasible"].mean())

    metrics = _calculate_target_metrics(
        details=details,
        targets=validation_targets,
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    details_path = output_dir / "physics_validation_details.csv"

    metrics_path = output_dir / "physics_validation_metrics.csv"

    summary_path = output_dir / "physics_validation_summary.json"

    details.to_csv(
        details_path,
        index=False,
    )

    metrics.to_csv(
        metrics_path,
        index=False,
    )

    available_plot_targets = [target for target in plot_targets if target in validation_targets]

    plot_paths = tuple(
        _plot_prediction_comparison(
            details=details,
            target=target,
            output_path=(output_dir / f"surrogate_vs_physics_{target}.png"),
        )
        for target in available_plot_targets
    )

    worst_target_row = metrics.sort_values(
        by=[
            "mean_relative_error",
            "target",
        ],
        ascending=[
            False,
            True,
        ],
        ignore_index=True,
    ).iloc[0]

    summary = {
        "generated_at": datetime.now(UTC).isoformat(),
        "designs_path": str(designs_path),
        "benchmark_config_path": str(benchmark_config_path),
        "physics_seed": seed,
        "design_count": int(len(details)),
        "validated_targets": list(validation_targets),
        "validated_target_count": int(len(validation_targets)),
        "physics_feasible_count": int(details["physics_is_feasible"].sum()),
        "classifier_feasible_count": int(details["classifier_is_feasible"].sum()),
        "feasibility_agreement_rate": (feasibility_agreement_rate),
        "worst_target_by_mean_relative_error": {
            "target": str(worst_target_row["target"]),
            "mean_relative_error": float(worst_target_row["mean_relative_error"]),
        },
        "details_path": str(details_path),
        "metrics_path": str(metrics_path),
        "plot_paths": [str(path) for path in plot_paths],
    }

    summary_path.write_text(
        json.dumps(
            _json_safe(summary),
            indent=2,
            sort_keys=True,
            allow_nan=False,
        )
        + "\n",
        encoding="utf-8",
    )

    return PhysicsValidationArtifacts(
        details_path=details_path,
        metrics_path=metrics_path,
        summary_path=summary_path,
        plot_paths=plot_paths,
        design_count=len(details),
        validated_target_count=len(validation_targets),
        feasibility_agreement_rate=(feasibility_agreement_rate),
    )
